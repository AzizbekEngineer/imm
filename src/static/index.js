export const getProductBySlug = (slug) =>
  products.find((item) => item.slug === slug);

export const getRelatedProducts = (product, limit = 3) =>
  products
    .filter(
      (item) => item.category === product.category && item.id !== product.id,
    )
    .slice(0, limit);

